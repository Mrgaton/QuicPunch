import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {launchBrowser} from '../../../QuicPunchTests/Fixtures/BrowserFixture.mjs';

const output = new URL('../../../.artifacts/nettt-call-studio/', import.meta.url);
await mkdir(output, {recursive:true});
const browser = await launchBrowser();
try {
  const page = await browser.newPage({viewport:{width:1440,height:1150}});
  const errors=[], requests=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('request',request=>{if(/^https?:/.test(request.url()))requests.push(request.url());});
  await page.goto(new URL('index.html',import.meta.url).href);
  const input = name => page.locator(`[name="${name}"]`);
  const status = () => page.locator('#status').innerText();
  assert.equal(await input('fps').inputValue(),'60');
  assert.equal(await page.locator('#apply').isDisabled(),true);
  await page.screenshot({path:fileURLToPath(new URL('desktop.png',output)),fullPage:true});
  await page.locator('[data-profile="cinema"]').click();
  assert.equal(await input('fps').inputValue(),'24');
  assert.equal(await input('playout').inputValue(),'150');
  await page.locator('[data-track="camera"]').click();
  assert.equal(await input('fps').inputValue(),'30');
  await page.locator('[data-track="voice"]').click();
  assert.equal(await input('voiceBitrate').inputValue(),'96');
  assert.equal(await page.locator('#tab-video').isDisabled(),true);
  await page.locator('[data-track="screen"]').click();
  assert.equal(await input('fps').inputValue(),'24');
  await input('backend').selectOption('ffmpeg');
  await input('bitrate').fill('19');
  assert.equal(await input('vbv').isDisabled(),false);
  assert.equal(await input('preset').isDisabled(),false);
  await page.locator('#tab-diagnostics').click();
  await page.locator('#failNext').check();
  await page.locator('#apply').click();
  assert.match(await status(),/Fallo simulado/);
  assert.equal(await page.locator('#apply').isDisabled(),false);
  assert.match(await page.locator('#comparison').innerText(),/1920x1080/);
  await page.locator('#apply').click();
  assert.equal(await page.locator('#apply').isDisabled(),true);
  await page.locator('#save').click();
  await page.locator('[data-profile="game"]').click();
  await page.locator('#load').click();
  assert.equal(await input('fps').inputValue(),'24');
  await page.locator('#tab-video').click();
  await input('bitrate').fill('0');
  await page.locator('#apply').click();
  assert.match(await status(),/Revisa bitrate/);
  await page.locator('#reset').click();
  assert.equal(await input('bitrate').inputValue(),'19');
  await input('codec').selectOption('hevc');
  await page.locator('#tab-diagnostics').click();
  assert.match(await page.locator('#compatibility').innerText(),/No compatible/);
  await page.locator('#tab-latency').click();
  await page.locator('#tab-latency').press('ArrowRight');
  assert.equal(await page.locator('#tab-diagnostics').getAttribute('aria-selected'),'true');
  await page.locator('#tab-diagnostics').press('Home');
  assert.equal(await page.locator('#tab-video').getAttribute('aria-selected'),'true');
  await page.locator('#reset').click();
  await page.locator('#tab-latency').click();
  await page.screenshot({path:fileURLToPath(new URL('latency.png',output)),fullPage:true});
  await page.evaluate(()=>localStorage.setItem('nettt-call-studio-design-v1','{"schemaVersion":1,"tracks":{}}'));
  await page.locator('#load').click();
  assert.match(await status(),/bitrate de voz/);
  assert.equal(await input('fps').inputValue(),'24');
  await page.locator('#tab-video').click();
  for (const width of [390,320,768,1440]) {
    await page.setViewportSize({width,height:900});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,`Overflow at ${width}px`);
  }
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.locator('#save').isVisible(),true,'Mobile must retain profile actions');
  const downloaded = page.waitForEvent('download');
  await page.locator('#export').click();
  const download = await downloaded;
  assert.equal(download.suggestedFilename(),'nettt-perfil-diseno.json');
  await download.saveAs(fileURLToPath(new URL('profile.json',output)));
  await page.screenshot({path:fileURLToPath(new URL('mobile.png',output)),fullPage:true});
  assert.deepEqual(errors,[]);
  assert.deepEqual(requests,[], 'Prototype must not contact external services');
  console.log('PASS: isolated profiles, codec controls, apply/rollback, validation, persistence, compatibility, keyboard, responsive layout; no JS errors or network requests.');
} finally {await browser.close();}
