import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync(new URL('../../QuicNet.Shared/wwwroot/updates.js',import.meta.url),'utf8');
const nodes=new Map();
for(const id of ['updateVersion','updateStatus','updateMessage','updateAutomatic','updateLatest','updateLastCheck','updateProgress','updateCheck','updateInstall','updatePlatformHelp',
 ...['menuUpdate','mobileUpdate'].flatMap(prefix=>['Notice','Title','Detail','Progress','Install'].map(suffix=>prefix+suffix))])
 nodes.set(id,{textContent:'',checked:true,hidden:false,disabled:false,listeners:{},addEventListener(type,fn){this.listeners[type]=fn;}});
let status={CurrentVersion:'1.1.0',CurrentBuild:2,Platform:'android-arm64',Automatic:true,Stage:'ready',LatestVersion:'1.2.0',LatestBuild:3,Message:'Lista',Downloaded:10,Total:10};
const calls=[],events={};
let installWait, failure;
const appEvents={};
const sandbox={window:{QP:{state:{updates:status},on:(type,fn)=>appEvents[type]=fn,wsRequest:async(command,data)=>{calls.push([command,data]);if(failure)throw new Error(failure);if(command==='updates.install'&&installWait)await installWait;if(command==='updates.automatic')status.Automatic=data.enabled;appEvents.update_status(status);return status;}}},
 document:{hidden:false,getElementById:id=>nodes.get(id),addEventListener:(name,fn)=>events[name]=fn},setInterval:()=>{throw Error('Update polling is forbidden');},console,Date,JSON};
const poll=async()=>appEvents.update_status(status);
vm.runInNewContext(source,sandbox);
events.DOMContentLoaded();
await new Promise(r=>setImmediate(r));
assert.equal(nodes.get('updateStatus').textContent,'Lista para instalar');
assert.equal(nodes.get('updateInstall').hidden,false);
assert.match(nodes.get('updatePlatformHelp').textContent,/Android/);
for(const prefix of ['menuUpdate','mobileUpdate']) {
 assert.equal(nodes.get(prefix+'Notice').hidden,false,'Update is visible outside settings');
 assert.equal(nodes.get(prefix+'Install').textContent,'Instalar actualización');
 assert.equal(nodes.get(prefix+'Install').disabled,false);
}
nodes.get('updateAutomatic').checked=false;
await nodes.get('updateAutomatic').listeners.change({target:nodes.get('updateAutomatic')});
assert.equal(status.Automatic,false);
await nodes.get('updateInstall').listeners.click();
assert.ok(calls.some(([command])=>command==='updates.install'));
await nodes.get('mobileUpdateInstall').listeners.click();
await nodes.get('menuUpdateInstall').listeners.click();
assert.equal(calls.filter(([command])=>command==='updates.install').length,3,'Both menu buttons install directly');
status={...status,Stage:'current',LatestBuild:2,Message:'Al día'};
await nodes.get('updateCheck').listeners.click();
assert.equal(nodes.get('updateInstall').hidden,true);
assert.equal(nodes.get('updateStatus').textContent,'Al día');
assert.equal(nodes.get('mobileUpdateNotice').hidden,true);
assert.equal(nodes.get('menuUpdateNotice').hidden,true);
status={...status,Stage:'downloading',LatestBuild:3,Downloaded:3,Total:10};
await poll();
assert.equal(nodes.get('updateProgress').hidden,false);
assert.equal(nodes.get('updateProgress').value,3);
assert.equal(nodes.get('updateCheck').disabled,true);
assert.equal(nodes.get('mobileUpdateProgress').value,3);
assert.match(nodes.get('mobileUpdateDetail').textContent,/30 %/);
assert.equal(nodes.get('mobileUpdateInstall').disabled,true);
status={...status,Stage:'checking'};
await poll();
assert.equal(nodes.get('mobileUpdateNotice').hidden,false,'Checking again keeps a known update visible');
status={...status,Stage:'installing'};
await poll();
assert.match(nodes.get('mobileUpdateTitle').textContent,/Confirma/);
assert.equal(nodes.get('menuUpdateInstall').disabled,true);
status={...status,Stage:'ready',Platform:'win-x64'};
await poll();
assert.equal(nodes.get('menuUpdateInstall').textContent,'Instalar y reiniciar');
let finishInstall;
installWait=new Promise(resolve=>finishInstall=resolve);
const pending=nodes.get('menuUpdateInstall').listeners.click();
assert.equal(nodes.get('mobileUpdateInstall').disabled,true);
const before=calls.length;
await nodes.get('mobileUpdateInstall').listeners.click();
assert.equal(calls.length,before,'Repeated taps do not submit duplicate installations');
finishInstall();await pending;installWait=null;
failure='No se pudo abrir el instalador';
await nodes.get('mobileUpdateInstall').listeners.click();
assert.equal(nodes.get('mobileUpdateDetail').textContent,failure,'Action errors remain visible outside settings');
assert.equal(nodes.get('mobileUpdateInstall').disabled,false,'Failed action can be retried');
await poll();
assert.equal(nodes.get('mobileUpdateNotice').hidden,false,'Failed poll preserves the notice');
failure=null;
status={...status,Stage:'error',Message:'La descarga falló'};
await poll();
assert.equal(nodes.get('mobileUpdateDetail').textContent,status.Message);
assert.equal(nodes.get('mobileUpdateInstall').disabled,false);
sandbox.document.hidden=true;
status={...status,Stage:'current',LatestBuild:2};
const paused=calls.length;await poll();assert.equal(calls.length,paused);
sandbox.document.hidden=false;await poll();
await new Promise(r=>setImmediate(r));
assert.equal(nodes.get('menuUpdateNotice').hidden,true,'Returning from Android installer refreshes status');
status={...status,Stage:'error',LatestBuild:null};
await poll();
assert.equal(nodes.get('mobileUpdateNotice').hidden,true,'Offline without a known update does not invent one');
status={...status,Stage:'available',Channel:'beta',LatestChannel:'stable',LatestBuild:3};await poll();
assert.match(nodes.get('mobileUpdateDetail').textContent,/Estable/,'Beta subscribers see a stable promotion mislabeled as beta');
status={...status,LatestChannel:'beta'};await poll();
assert.match(nodes.get('mobileUpdateDetail').textContent,/Beta/);
console.log('PASS updates: actual release channel labels, global PC/Android notices, installation, progress, retry and settings');
