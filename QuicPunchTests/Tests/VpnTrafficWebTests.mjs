import {readFileSync} from 'node:fs';
import {Script, createContext} from 'node:vm';
import assert from 'node:assert/strict';
const context = createContext({ window: {}, document: { addEventListener() {} } });
new Script(readFileSync(new URL('../../QuicNet.Shared/wwwroot/vpn-traffic.js', import.meta.url), 'utf8')).runInContext(context);
const History = context.window.VpnTrafficHistory;
const history = new History();
const sample = (rx, tx, at, active = true) => history.sample({ totalRxBytes: rx, totalTxBytes: tx, active }, at);
sample(10000, 20000, 1000);
assert.equal(history.rates(1000).rx, null, 'Lifetime counters establish a baseline without a false spike');
sample(14000, 22000, 3000);
assert.equal(history.rates(3000).rx, 2000, 'RX uses elapsed seconds');
assert.equal(history.rates(3000).tx, 1000, 'TX is calculated independently');
sample(14000, 22000, 3010);
assert.equal(history.points.length, 2, 'Duplicate UI refreshes do not distort the sampling interval');
sample(15000, 24000, 4000);
assert.equal(history.rates(4000).rx, 1000);
assert.equal(history.rates(4000).tx, 2000);
assert.equal(history.rates(10000).rx, null, 'Stale speed becomes unavailable');
sample(1, 1, 5000);
assert.equal(history.rates(5000).rx, null, 'Counter reset breaks the graph instead of producing negative traffic');
sample(1001, 501, 6000);
assert.equal(history.rates(6000).rx, 1000, 'Sampling recovers after a counter reset');
history.disconnect();
assert.equal(history.rates(6000).rx, null, 'Disconnect clears the displayed live speed');
sample(9000, 9000, 7000);
assert.equal(history.rates(7000).rx, null, 'Reconnect establishes a fresh baseline');
sample(10000, 10000, 30000);
assert.equal(history.rates(30000).rx, null, 'Long gaps do not turn into artificial traffic');
sample(10000, 10000, 31000, false);
assert.equal(history.rates(31000).rx, 0, 'Stopped adapter reports zero speed');
sample(50000, 50000, 32000);
assert.equal(history.rates(32000).rx, null, 'Restarting an adapter establishes a new baseline');
history.sample({ totalRxBytes: NaN, totalTxBytes: -1 }, 33000);
assert.equal(history.points.at(-1).at, 32000, 'Invalid counters are ignored');
for (let i = 1; i < 2000; i++) sample(50000 + i * 500, 50000 + i * 100, 32000 + i * 500);
assert.ok(history.points.length <= 601 && history.points.at(-1).at - history.points[0].at <= 300000, 'History is bounded to five minutes');
console.log('PASS VPN traffic: elapsed-time RX/TX rates, duplicate refreshes, counter resets, stale data, disconnect/reconnect, inactive adapter and bounded history');
