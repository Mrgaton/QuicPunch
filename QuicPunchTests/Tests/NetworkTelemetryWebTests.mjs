import {readFileSync} from 'node:fs';
import {Script, createContext} from 'node:vm';
import assert from 'node:assert/strict';
const context=createContext({window:{},document:{addEventListener(){}}});
new Script(readFileSync(new URL('../../QuicNet.Shared/wwwroot/network-telemetry.js',import.meta.url),'utf8')).runInContext(context);
const {History,unique}=context.window.NetworkTelemetry;
const session=(tx,rx,sent=100,lost=0,extra={})=>({peerId:'a',protocolId:'chat',transportType:'Wan',telemetry:{sendTotalBytes:tx,recvTotalBytes:rx,sendTotalPackets:sent,sendSuspectedLostPackets:lost,rttMs:12,sendCongestionWindow:8192,nativeLocalEndpoint:'192.0.2.1:5000',nativeRemoteEndpoint:'192.0.2.2:5000',...extra}});
const history=new History();
let point=history.sample([session(100000,200000)],1000);
assert.equal(point.tx,null,'First sample treated lifetime bytes as speed');
point=history.sample([session(102500,205000,200,2)],3500);
assert.equal(point.tx,1000);assert.equal(point.rx,2000);assert.equal(point.loss,2);assert.equal(point.rtt,12);assert.equal(point.cwnd,8192);
const duplicate={...session(102500,205000),protocolId:'voice'};
assert.equal(unique([session(102500,205000),duplicate]).length,1,'Shared transport counted per protocol');
assert.equal(unique([session(1,2),session(3,4,100,0,{nativeRemoteEndpoint:'192.0.2.3:5000'})]).length,2,'Distinct physical connections were merged');
assert.equal(history.sample([session(999999,999999)],3800),null,'Burst status event was sampled too soon');
point=history.sample([session(105000,210000,300,3)],6000);
assert.equal(point.tx,1000,'Burst status changed the counter baseline');
assert.equal(point.loss,1,'Loss is not based on the interval');
point=history.sample([session(10,20,1,0)],8500);assert.equal(point.tx,null,'Reset counters caused a negative rate');
point=history.sample([session(2510,5020,101,0)],11000);assert.equal(point.tx,1000);
point=history.sample([],13500);assert.equal(point.connections,0);assert.equal(point.tx,0);assert.equal(point.rtt,null);
point=history.sample([session(500000,100000)],16000);assert.equal(point.tx,null,'Reconnect generated a traffic spike');
point=history.sample([session(600000,200000)],46000);assert.equal(point.tx,null,'A suspended tab averaged a stale interval');
point=history.sample([{peerId:'missing'}],48500);assert.equal(point.rtt,null);assert.equal(point.cwnd,null);assert.equal(point.loss,null);
point=history.sample([session(Infinity,NaN,0,0,{rttMs:NaN,sendCongestionWindow:Infinity})],51000);assert.equal(point.tx,null);assert.equal(point.rtt,null);assert.equal(point.cwnd,null);
for(let i=0;i<1000;i++) history.sample([session(i*100,i*200)],55000+i*1000);
assert.ok(history.points.length<=600&&history.points.every(p=>p.at>=history.points.at(-1).at-600000),'History grows without bounds');
point=history.sample([session(1,2)],1000);assert.equal(history.points.length,1);assert.equal(point.tx,null,'Clock rollback retained stale rates');
console.log('PASS network history: real interval rates/loss, connection deduplication, resets, reconnects, missing data, long gaps and bounded memory');
